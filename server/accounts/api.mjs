const DEFAULT_SESSION_DAYS = 30;
const BODY_LIMIT = AVATAR_MAX_BYTES + 64 * 1024;
const SYNC_HISTORY_MS = 30 * 24 * 60 * 60 * 1000;

/* Route limits. Generous enough for a person, tight enough for a script. */
const DEFAULT_LIMITS = {
  register: { windowMs: 10 * 60_000, max: 10 },
  login: { windowMs: 5 * 60_000, max: 20 },
  friendRequest: { windowMs: 5 * 60_000, max: 30 },
  message: { windowMs: 60_000, max: 120 },
};

function send(res, status, payload, headers = {}) {
  const body = JSON.stringify(payload ?? {});
  res.writeHead(status, {
    "content-type": "application/json; charset=utf-8",
    "content-length": Buffer.byteLength(body),
    "cache-control": "no-store",
    ...headers,
  });
  res.end(body);
}

function fail(res, status, code, message, headers = {}) {
  send(res, status, { error: { code, message } }, headers);
}

async function readJson(req, res) {
  const length = Number(req.headers["content-length"] ?? 0);
  if (Number.isFinite(length) && length > BODY_LIMIT) {
    fail(res, 413, "BODY_TOO_LARGE", "That request is too large.");
    return { handled: true };
  }
  const type = String(req.headers["content-type"] ?? "");
  if (!type.includes("application/json")) {
    fail(res, 415, "UNSUPPORTED_MEDIA_TYPE", "Requests must be sent as application/json.");
    return { handled: true };
  }
  const chunks = [];
  let size = 0;
  for await (const chunk of req) {
    size += chunk.length;
    if (size > BODY_LIMIT) {
      fail(res, 413, "BODY_TOO_LARGE", "That request is too large.");
      return { handled: true };
    }
    chunks.push(chunk);
  }
  if (chunks.length === 0) return { body: {} };
  try {
    const parsed = JSON.parse(Buffer.concat(chunks).toString("utf8"));
    if (parsed === null || typeof parsed !== "object" || Array.isArray(parsed)) {
      fail(res, 400, "INVALID_BODY", "Expected a JSON object.");
      return { handled: true };
    }
    return { body: parsed };
  } catch {
    fail(res, 400, "INVALID_JSON", "That request body is not valid JSON.");
    return { handled: true };
  }
}

function isSecureRequest(req) {
  const proto = String(req.headers["x-forwarded-proto"] ?? "").split(",")[0].trim();
  return proto === "https" || Boolean(req.socket.encrypted);
}

function clientAddress(req, trustProxy) {
  if (trustProxy) {
    const forwarded = String(req.headers["x-forwarded-for"] ?? "").split(",")[0].trim();
    if (forwarded) return forwarded;
  }
  return req.socket.remoteAddress ?? "unknown";
}

/** Blocks cross-site form posts from riding an existing session cookie. */
function sameOrigin(req) {
  const origin = req.headers.origin;
  if (!origin) return true;
  try {
    return new URL(origin).host === req.headers.host;
  } catch {
    return false;
  }
}

