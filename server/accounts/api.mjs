/*
 * CrystalOS — accounts API
 *
 * A plain `node:http` handler (no framework, no dependency) mounted on the
 * existing CrystalOS backend. It is the only place accounts, friend codes,
 * friend requests and friendships are written; the browser talks to it through
 * the Vite proxy in development and through the same origin in production.
 *
 * Security rules implemented here, all of them server-side:
 *
 *   - Passwords are scrypt-hashed (see security.mjs); plaintext never persists.
 *   - Sessions are opaque tokens in an HttpOnly SameSite=Lax cookie. The DB
 *     stores only the SHA-256 digest of a token.
 *   - A friend code is generated by `createUser` and is never writable. Any
 *     request that carries a `friendCode` field is rejected outright, and no
 *     route updates the column.
 *   - Every mutating route works from the session user. The client cannot name
 *     the acting account, cannot answer someone else's request, and cannot
 *     address a conversation it is not part of (conversations are looked up by
 *     peer id and always resolved against the session user).
 *   - Requests are rate limited per client address, and bodies are size-capped.
 */

