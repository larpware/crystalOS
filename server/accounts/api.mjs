export function createAccountsApi(options = {}) {
  const store = options.store ?? openAccountsStore();
  const sessionDays = Number(options.sessionDays ?? process.env.CRESCENT_SESSION_DAYS ?? DEFAULT_SESSION_DAYS);
  const trustProxy = options.trustProxy ?? process.env.CRESCENT_TRUST_PROXY === "1";
  const limits = {
    register: createRateLimiter(options.limits?.register ?? DEFAULT_LIMITS.register),
    login: createRateLimiter(options.limits?.login ?? DEFAULT_LIMITS.login),
    friendRequest: createRateLimiter(options.limits?.friendRequest ?? DEFAULT_LIMITS.friendRequest),
    message: createRateLimiter(options.limits?.message ?? DEFAULT_LIMITS.message),
    socialPost: createRateLimiter(options.limits?.socialPost ?? DEFAULT_LIMITS.socialPost),
    socialComment: createRateLimiter(options.limits?.socialComment ?? DEFAULT_LIMITS.socialComment),
    socialAction: createRateLimiter(options.limits?.socialAction ?? DEFAULT_LIMITS.socialAction),
  };

  const ADMIN_USERNAMES = envAdmins();

  /** Moderation authority: the role column, or the environment's list. */
  function isAdmin(user) {
    return user?.role === "admin" || ADMIN_USERNAMES.has(String(user?.username ?? "").toLowerCase());
  }

  let sweeps = 0;

  function setCookie(res, token, secure) {
    res.setHeader(
      "set-cookie",
      serializeCookie(SESSION_COOKIE, token, { maxAge: sessionDays * 24 * 3600, secure }),
    );
  }

  function clearCookie(res, secure) {
    res.setHeader("set-cookie", serializeCookie(SESSION_COOKIE, "", { clear: true, secure }));
  }

  /** Resolves the session (if any) and returns the fresh user row. */
  function currentUser(req, { touch = true } = {}) {
    const token = parseCookies(req.headers.cookie)[SESSION_COOKIE];
    if (!token) return null;
    const session = store.sessionByTokenHash(hashToken(token));
    if (!session) return null;
    const now = Date.now();
    if (session.expires_at <= now) {
      store.deleteSession(session.token_hash);
      return null;
    }
    const user = store.userById(session.user_id);
    if (!user) {
      store.deleteSession(session.token_hash);
      return null;
    }
    // Presence is a by-product of ordinary authenticated traffic. Writes are
    // throttled so a polling client does not write once per request.
    if (touch && now - user.last_seen_at > 15_000) {
      store.touchUser(user.id, now);
      user.last_seen_at = now;
    }
    return user;
  }

  function startSession(req, res, user) {
    const token = createSessionToken();
    const now = Date.now();
    store.createSession({
      tokenHash: hashToken(token),
      userId: user.id,
      createdAt: now,
      expiresAt: now + sessionDays * 24 * 3600 * 1000,
    });
    setCookie(res, token, isSecureRequest(req));
    store.pruneSessions(now);
  }

  function limitOr429(limiter, key, res) {
    const verdict = limiter.take(key);
    if (verdict.ok) return false;
    fail(res, 429, "RATE_LIMITED", "Too many attempts. Try again in a moment.", {
      "retry-after": String(verdict.retryAfter),
    });
    return true;
  }

  /**
   * Resolves the session user, or answers 401. Blind probing of protected
   * routes is metered by the optional limiter so unauthenticated traffic
   * cannot be used to hammer the server either.
   */
  function requireUser(req, res, limiter) {
    const user = currentUser(req);
    if (user) return user;
    if (limiter) {
      const verdict = limiter.take(`anon:${clientAddress(req, trustProxy)}`);
      if (!verdict.ok) {
        fail(res, 429, "RATE_LIMITED", "Too many attempts. Try again in a moment.", {
          "retry-after": String(verdict.retryAfter),
        });
        return null;
      }
    }
    fail(res, 401, "NOT_SIGNED_IN", "Sign in to do that.");
    return null;
  }

  function friendPayload(row, now) {
    return {
      id: row.id,
      username: row.username,
      displayName: row.display_name,
      friendCode: formatFriendCode(row.friend_code),
      avatar: row.avatar ?? undefined,
      rarity: row.rarity ?? undefined,
      tags: tagsOf(row),
      online: row.last_seen_at > now - 60_000,
      lastSeenAt: row.last_seen_at,
    };
  }

  /* ---- route handlers -------------------------------------------------- */

  function rejectFriendCodeField(body, res) {
    if (!Object.prototype.hasOwnProperty.call(body, "friendCode")) return false;
    fail(
      res,
      400,
      "FRIEND_CODE_IMMUTABLE",
      "Friend codes are generated by the server and cannot be chosen or changed.",
    );
    return true;
  }

  async function handleRegister(req, res, { body }) {
    if (limitOr429(limits.register, `register:${clientAddress(req, trustProxy)}`, res)) return;
    if (rejectFriendCodeField(body, res)) return;

    const username = validateUsername(body.username);
    if (username.error) return fail(res, 400, "INVALID_USERNAME", username.error);
    const password = validatePassword(body.password);
    if (password.error) return fail(res, 400, "INVALID_PASSWORD", password.error);
    const displayName = validateDisplayName(body.displayName, username.value);
    if (displayName.error) return fail(res, 400, "INVALID_DISPLAY_NAME", displayName.error);

    const { salt, hash } = await hashPassword(password.value);

    // The account and its first session are written in one transaction, so a
    // failure part-way through cannot leave an account nobody can sign into.
    let user;
    try {
      user = store.transaction(() => {
        const created = store.createUser({
          username: username.value,
          displayName: displayName.value,
          passwordSalt: salt,
          passwordHash: hash,
          createdAt: Date.now(),
        });
        // The first account on a fresh database is the project owner and gets
        // moderation authority. CRESCENT_ADMINS can name more, by username.
        const isFirst =
          Number(store.db.prepare("SELECT COUNT(*) AS n FROM users").get().n) === 1;
        if (isFirst || ADMIN_USERNAMES.has(username.value.toLowerCase())) {
          store.db.prepare("UPDATE users SET role = 'admin' WHERE id = ?").run(created.id);
          created.role = "admin";
        }
        startSession(req, res, created);
        return created;
      });
    } catch (error) {
      if (error?.code === "USERNAME_TAKEN") {
        return fail(res, 409, "USERNAME_TAKEN", "That username is already taken.");
      }
      throw error;
    }

    send(res, 201, { user: publicUser(user) });
  }

  async function handleLogin(req, res, { body }) {
    const address = clientAddress(req, trustProxy);
    if (limitOr429(limits.login, `login:${address}`, res)) return;

    const identifier = cleanText(String(body.identifier ?? body.username ?? "")).trim();
    const password = typeof body.password === "string" ? body.password : "";
    if (!identifier || !password) {
      return fail(res, 400, "MISSING_CREDENTIALS", "Enter your username and password.");
    }

    // A friend code is accepted as a convenience alias for the username; the
    // password is still required, and failure messages never reveal which
    // accounts exist.
    const canonical = normalizeFriendCode(identifier);
    const user =
      store.userByUsername(identifier) ??
      (isWellFormedFriendCode(canonical) ? store.userByFriendCode(canonical) : null);

    const ok = user ? await verifyPassword(password, user.password_salt, user.password_hash) : false;
    if (!ok) {
      return fail(res, 401, "INVALID_CREDENTIALS", "Incorrect username or password.");
    }

    startSession(req, res, user);
    send(res, 200, { user: publicUser(user) });
  }

  function handleMe(req, res) {
    const user = currentUser(req);
    send(res, 200, { server: true, user: publicUser(user) });
  }

  function handleProfileUpdate(req, res, { body, user }) {
    if (rejectFriendCodeField(body, res)) return;
    const patch = {};
    if (body.username !== undefined) {
      const username = validateUsername(body.username);
      if (username.error) return fail(res, 400, "INVALID_USERNAME", username.error);
      patch.username = username.value;
    }
    if (body.displayName !== undefined) {
      const displayName = validateDisplayName(body.displayName, user.username);
      if (displayName.error) return fail(res, 400, "INVALID_DISPLAY_NAME", displayName.error);
      patch.displayName = displayName.value;
    }
    if (body.bio !== undefined) {
      const bio = validateBio(body.bio);
      if (bio.error) return fail(res, 400, "INVALID_BIO", bio.error);
      patch.bio = bio.value;
    }
    if (body.avatar !== undefined) {
      const avatar = validateAvatar(body.avatar);
      if (avatar.error) return fail(res, 400, "INVALID_AVATAR", avatar.error);
      patch.avatar = avatar.value;
    }
    if (body.privateAccount !== undefined) {
      if (typeof body.privateAccount !== "boolean") {
        return fail(res, 400, "INVALID_PRIVACY", "Private account must be true or false.");
      }
      patch.privateAccount = body.privateAccount;
    }
    if (Object.keys(patch).length === 0) {
      return fail(res, 400, "NOTHING_TO_UPDATE", "Nothing to update.");
    }

    let updated;
    try {
      updated = store.updateUser(user.id, patch);
    } catch (error) {
      if (error?.code === "USERNAME_TAKEN") {
        return fail(res, 409, "USERNAME_TAKEN", "That username is already taken.");
      }
      throw error;
    }
    send(res, 200, { user: publicUser(updated) });
  }

  async function handlePasswordChange(req, res, { body, user }) {
    if (rejectFriendCodeField(body, res)) return;
    const current = typeof body.currentPassword === "string" ? body.currentPassword : "";
    const next = validatePassword(body.newPassword);
    if (next.error) return fail(res, 400, "INVALID_PASSWORD", next.error);
    const ok = await verifyPassword(current, user.password_salt, user.password_hash);
    if (!ok) return fail(res, 403, "WRONG_PASSWORD", "Current password is incorrect.");

    const { salt, hash } = await hashPassword(next.value);
    store.updatePassword(user.id, salt, hash);
    // Other sessions are dropped: a password change should end them.
    store.deleteSessionsForUser(user.id);
    const fresh = store.userById(user.id);
    startSession(req, res, fresh);
    send(res, 200, { user: publicUser(fresh) });
  }

  async function handleDeleteAccount(req, res, { body, user }) {
    const password = typeof body.password === "string" ? body.password : "";
    const ok = await verifyPassword(password, user.password_salt, user.password_hash);
    if (!ok) return fail(res, 403, "WRONG_PASSWORD", "Enter your password to delete the account.");
    store.deleteSessionsForUser(user.id);
    store.deleteUser(user.id);
    clearCookie(res, isSecureRequest(req));
    send(res, 200, { ok: true });
  }

  function handleSync(req, res, url, user) {
    const now = Date.now();
    const requested = Number(url.searchParams.get("since") ?? now - 60_000);
    const since = Number.isFinite(requested)
      ? Math.min(now, Math.max(now - SYNC_HISTORY_MS, Math.floor(requested)))
      : now - 60_000;

    const peerCache = new Map();
    const peerFor = (id) => {
      if (!peerCache.has(id)) peerCache.set(id, store.userById(id));
      return peerCache.get(id);
    };

    const messages = store.newMessagesForUser(user.id, since).map((row) => {
      const peerId = row.user_a === user.id ? row.user_b : row.user_a;
      const peer = peerFor(peerId);
      return {
        conversationId: row.conversation_id,
        peer: peer ? friendPayload(peer, now) : null,
        message: {
          id: row.id,
          authorId: row.author_id,
          authorName: peer ? peer.display_name : "",
          body: row.body,
          sentAt: row.sent_at,
        },
      };
    });

    const incoming = [];
    const outgoing = [];
    for (const row of store.incomingRequests(user.id)) {
      incoming.push({ id: row.request_id, from: friendPayload(row, now), createdAt: row.request_created_at });
    }
    for (const row of store.outgoingRequests(user.id)) {
      outgoing.push({
        id: row.request_id,
        to: friendPayload(row, now),
        status: row.request_status,
        createdAt: row.request_created_at,
      });
    }

    send(res, 200, {
      serverTime: now,
      since,
      user: publicUser(user, now),
      friends: store.friendsOf(user.id, now),
      incoming,
      outgoing,
      messages,
    });
  }

  function handleFriendRequest(req, res, { body, user }) {
    if (limitOr429(limits.friendRequest, `friend:${user.id}`, res)) return;

    const canonical = normalizeFriendCode(body.code ?? body.friendCode ?? "");
    if (!canonical) return fail(res, 400, "FRIEND_CODE_INVALID", "Enter a friend code.");
    if (!isWellFormedFriendCode(canonical)) {
      return fail(
        res,
        400,
        "FRIEND_CODE_INVALID",
        "That is not a CrystalOS friend code. Codes look like CR-7K4M-9Q2X.",
      );
    }
    const target = store.userByFriendCode(canonical);
    if (!target) {
      return fail(res, 404, "FRIEND_CODE_NOT_FOUND", "No account has that friend code.");
    }
    if (target.id === user.id) {
      return fail(
        res,
        400,
        "SELF_REQUEST",
        "That is your own friend code — share it with the other person instead.",
      );
    }
    if (store.areFriends(user.id, target.id)) {
      return fail(res, 409, "ALREADY_FRIENDS", `${target.display_name} is already a friend.`);
    }

    const outcome = store.transaction(() => {
      const reverse = store.requestBetween(target.id, user.id);
      if (reverse && reverse.status === "pending") return { conflict: "reverse" };
      const forward = store.requestBetween(user.id, target.id);
      if (forward && forward.status === "pending") return { conflict: "duplicate" };
      const request = store.upsertPendingRequest({
        id: createId("req"),
        fromId: user.id,
        toId: target.id,
        at: Date.now(),
      });
      return { request };
    });

    if (outcome.conflict === "duplicate") {
      return fail(res, 409, "REQUEST_ALREADY_SENT", `A request is already waiting for ${target.display_name}.`);
    }
    if (outcome.conflict === "reverse") {
      return fail(
        res,
        409,
        "REQUEST_ALREADY_RECEIVED",
        `${target.display_name} already sent you a request — accept it from your incoming requests.`,
      );
    }

    send(res, 201, {
      request: {
        id: outcome.request.id,
        to: friendPayload(target, Date.now()),
        status: "pending",
        createdAt: outcome.request.created_at,
      },
    });
  }

  function requestForActor(res, requestId, user, expect) {
    const request = store.requestById(requestId);
    if (!request) {
      fail(res, 404, "REQUEST_NOT_FOUND", "That friend request no longer exists.");
      return null;
    }
    if (expect === "recipient" && request.to_user !== user.id) {
      fail(res, 403, "NOT_YOUR_REQUEST", "That request was not sent to you.");
      return null;
    }
    if (expect === "sender" && request.from_user !== user.id) {
      fail(res, 403, "NOT_YOUR_REQUEST", "That request was not sent by you.");
      return null;
    }
    if (request.status !== "pending") {
      fail(res, 409, "REQUEST_ALREADY_ANSWERED", "That request has already been answered.");
      return null;
    }
    return request;
  }

  function handleAccept(req, res, requestId, user) {
    const request = requestForActor(res, requestId, user, "recipient");
    if (!request) return;
    const sender = store.userById(request.from_user);
    if (!sender) return fail(res, 404, "ACCOUNT_NOT_FOUND", "That account no longer exists.");

    store.transaction(() => {
      store.addFriendship(request.from_user, request.to_user, Date.now());
      store.setRequestStatus(request.id, "accepted", Date.now());
      store.deleteRequestsBetween(request.from_user, request.to_user);
    });
    send(res, 200, { friend: friendPayload(sender, Date.now()) });
  }

  function handleDecline(req, res, requestId, user) {
    const request = requestForActor(res, requestId, user, "recipient");
    if (!request) return;
    store.setRequestStatus(request.id, "declined", Date.now());
    send(res, 200, { ok: true });
  }

  function handleCancel(req, res, requestId, user) {
    const request = store.requestById(requestId);
    if (!request) return fail(res, 404, "REQUEST_NOT_FOUND", "That friend request no longer exists.");
    if (request.from_user !== user.id) {
      return fail(res, 403, "NOT_YOUR_REQUEST", "That request was not sent by you.");
    }
    store.deleteRequest(request.id);
    send(res, 200, { ok: true });
  }

  function handleRemoveFriend(req, res, peerId, user) {
    const peer = store.userById(peerId);
    if (!peer) return fail(res, 404, "ACCOUNT_NOT_FOUND", "That account no longer exists.");
    const friendship = store.friendshipBetween(user.id, peer.id);
    if (!friendship) return fail(res, 404, "NOT_FRIENDS", `${peer.display_name} is not on your friends list.`);
    store.removeFriendship(user.id, peer.id);
    store.deleteRequestsBetween(user.id, peer.id);
    send(res, 200, { ok: true });
  }

  function handleSendMessage(req, res, peerId, { body, user }) {
    const peer = store.userById(peerId);
    if (!peer) return fail(res, 404, "ACCOUNT_NOT_FOUND", "That account no longer exists.");
    if (peer.id === user.id) {
      return fail(res, 400, "SELF_CONVERSATION", "You cannot message yourself.");
    }
    if (!store.areFriends(user.id, peer.id)) {
      return fail(res, 403, "NOT_FRIENDS", `${peer.display_name} is not on your friends list.`);
    }
    if (limitOr429(limits.message, `message:${user.id}`, res)) return;

    const text = validateMessageBody(body.body);
    if (text.error) return fail(res, 400, "INVALID_MESSAGE", text.error);

    const now = Date.now();
    const conversation = store.ensureConversation(user.id, peer.id, now);
    const proposed = validateMessageId(body.clientId).value;
    const stored = store.insertMessage({
      id: proposed ?? createId("msg"),
      conversationId: conversation.id,
      authorId: user.id,
      body: text.value,
      sentAt: now,
    });

    send(res, 201, {
      conversationId: conversation.id,
      peer: friendPayload(peer, now),
      message: {
        id: stored.id,
        authorId: stored.author_id,
        authorName: user.display_name,
        body: stored.body,
        sentAt: stored.sent_at,
      },
    });
  }

  function handleConversationHistory(req, res, url, peerId, user) {
    const peer = store.userById(peerId);
    if (!peer) return fail(res, 404, "ACCOUNT_NOT_FOUND", "That account no longer exists.");
    // Conversations are never addressed by id: resolving through the session
    // user means a caller can only ever read a thread it is part of.
    const conversation = store.conversationFor(user.id, peer.id);
    if (!conversation) {
      send(res, 200, { conversationId: conversationIdFor(user.id, peer.id), peer: friendPayload(peer, Date.now()), messages: [] });
      return;
    }
    const limitRaw = Number(url.searchParams.get("limit") ?? 100);
    const limit = Number.isFinite(limitRaw) ? Math.min(200, Math.max(1, Math.floor(limitRaw))) : 100;
    const beforeRaw = Number(url.searchParams.get("before") ?? Number.MAX_SAFE_INTEGER);
    const before = Number.isFinite(beforeRaw) ? Math.floor(beforeRaw) : Number.MAX_SAFE_INTEGER;

    const messages = store.messagesInConversation(conversation.id, { before, limit }).map((row) => ({
      id: row.id,
      authorId: row.author_id,
      authorName: row.author_id === user.id ? user.display_name : peer.display_name,
      body: row.body,
      sentAt: row.sent_at,
    }));

    send(res, 200, {
      conversationId: conversation.id,
      peer: friendPayload(peer, Date.now()),
      messages,
    });
  }

  /* ---- Crystal Social --------------------------------------------------- */

  function handleCreatePost(req, res, { body, user }) {
    if (limitOr429(limits.socialPost, `post:${user.id}`, res)) return;
    const postBody = validatePostBody(body.body);
    if (postBody.error) return fail(res, 400, "INVALID_POST", postBody.error);
    const image = validatePostImage(body.image);
    if (image.error) return fail(res, 400, "INVALID_IMAGE", image.error);
    const post = store.transaction(() =>
      store.social.createPost(user.id, { body: postBody.value, image: image.value }),
    );
    send(res, 201, { post });
  }

  /** Loads a post for an action, or answers the standard errors. */
  function withPost(res, user, postId) {
    const post = store.social.postById(postId);
    if (!post || post.deleted_at) {
      fail(res, 404, "POST_NOT_FOUND", "That post is gone.");
      return null;
    }
    if (!store.social.canViewPosts(user.id, post.author_id)) {
      fail(res, 403, "NOT_VISIBLE", "That post is not visible to you.");
      return null;
    }
    return post;
  }

  function handleNotifications(req, res, url, user) {
    const sinceRaw = Number(url.searchParams.get("since") ?? 0);
    const since = Number.isFinite(sinceRaw) ? Math.max(0, Math.floor(sinceRaw)) : 0;
    send(res, 200, { notifications: store.social.notifications(user.id, since) });
  }

  function handleProfileFetch(res, url, user, username) {
    const profile = store.social.profile(user.id, username);
    if (!profile) return fail(res, 404, "ACCOUNT_NOT_FOUND", "That account no longer exists.");
    if (profile.blocked) {
      return fail(res, 403, "BLOCKED", "You cannot view that account.");
    }
    send(res, 200, { profile });
  }

  /* ---- router ---------------------------------------------------------- */

  const API_PREFIX = "/api/accounts";

  /** Returns true when the request belonged to the accounts API. */
  async function handle(req, res, url) {
    const path = url.pathname;
    if (path !== API_PREFIX && !path.startsWith(`${API_PREFIX}/`)) return false;

    const segments = path.slice(API_PREFIX.length).split("/").filter(Boolean);
    const method = req.method ?? "GET";

    if (method !== "GET" && method !== "HEAD" && !sameOrigin(req)) {
      fail(res, 403, "CROSS_ORIGIN", "Cross-origin requests are not allowed.");
      return true;
    }

    sweeps += 1;
    if (sweeps % 200 === 0) for (const limiter of Object.values(limits)) limiter.sweep();

    try {
      // The body is read once, up front, for every mutating request. Replying
      // before the request stream is consumed would leave keep-alive
      // connections in an unusable state, so no route gets to skip this — not
      // even the ones that answer 401 before they need the body.
      let body = {};
      if (method !== "GET" && method !== "HEAD") {
        const hasBody =
          Number(req.headers["content-length"] ?? 0) > 0 || Boolean(req.headers["transfer-encoding"]);
        if (hasBody) {
          const parsed = await readJson(req, res);
          if (parsed.handled) return true;
          body = parsed.body;
        }
      }

      // POST /api/accounts/register
      if (method === "POST" && segments.length === 1 && segments[0] === "register") {
        await handleRegister(req, res, { body });
        return true;
      }

      // POST /api/accounts/login
      if (method === "POST" && segments.length === 1 && segments[0] === "login") {
        await handleLogin(req, res, { body });
        return true;
      }

      // POST /api/accounts/logout
      if (method === "POST" && segments.length === 1 && segments[0] === "logout") {
        const token = parseCookies(req.headers.cookie)[SESSION_COOKIE];
        if (token) store.deleteSession(hashToken(token));
        clearCookie(res, isSecureRequest(req));
        send(res, 200, { ok: true });
        return true;
      }

      // GET /api/accounts/me — the client's session bootstrap. Answers 200 with
      // `user: null` when nobody is signed in, so the shell never has to treat
      // "no session" as an error.
      if (method === "GET" && segments.length === 1 && segments[0] === "me") {
        handleMe(req, res);
        return true;
      }

      // GET /api/accounts/rarities — the rarity guide, from the same table the
      // draw uses. Public on purpose: someone deciding whether to sign up should
      // be able to read the odds before they have an account.
      if (method === "GET" && segments.length === 1 && segments[0] === "rarities") {
        send(res, 200, rarityGuide());
        return true;
      }

      // Everything below requires a session.
      if (segments.length === 1 && segments[0] === "me") {
        const user = requireUser(req, res, limits.login);
        if (!user) return true;
        if (method === "PATCH") {
          handleProfileUpdate(req, res, { body, user });
          return true;
        }
        if (method === "DELETE") {
          await handleDeleteAccount(req, res, { body, user });
          return true;
        }
      }

      // POST /api/accounts/me/password
      if (method === "POST" && segments.length === 2 && segments[0] === "me" && segments[1] === "password") {
        const user = requireUser(req, res, limits.login);
        if (!user) return true;
        await handlePasswordChange(req, res, { body, user });
        return true;
      }

      // GET /api/accounts/sync
      if (method === "GET" && segments.length === 1 && segments[0] === "sync") {
        const user = requireUser(req, res);
        if (!user) return true;
        handleSync(req, res, url, user);
        return true;
      }

      // POST /api/accounts/friend-requests
      if (method === "POST" && segments.length === 1 && segments[0] === "friend-requests") {
        const user = requireUser(req, res);
        if (!user) return true;
        handleFriendRequest(req, res, { body, user });
        return true;
      }

      // /api/accounts/friend-requests/:id[/accept|/decline]
      if (segments[0] === "friend-requests" && segments.length >= 2) {
        const user = requireUser(req, res);
        if (!user) return true;
        const requestId = decodeURIComponent(segments[1]);
        if (method === "DELETE" && segments.length === 2) {
          handleCancel(req, res, requestId, user);
          return true;
        }
        if (method === "POST" && segments[2] === "accept") {
          handleAccept(req, res, requestId, user);
          return true;
        }
        if (method === "POST" && segments[2] === "decline") {
          handleDecline(req, res, requestId, user);
          return true;
        }
      }

      // DELETE /api/accounts/friends/:userId
      if (method === "DELETE" && segments[0] === "friends" && segments.length === 2) {
        const user = requireUser(req, res);
        if (!user) return true;
        handleRemoveFriend(req, res, decodeURIComponent(segments[1]), user);
        return true;
      }

      /* ---- Crystal Social ---- */

      // GET /api/accounts/feed?before=&limit=
      if (method === "GET" && segments.length === 1 && segments[0] === "feed") {
        const user = requireUser(req, res, limits.login);
        if (!user) return true;
        const beforeRaw = Number(url.searchParams.get("before") ?? 0);
        const limitRaw = Number(url.searchParams.get("limit") ?? 20);
        send(res, 200, {
          feed: store.social.feedPage(user.id, {
            before: Number.isFinite(beforeRaw) && beforeRaw > 0 ? beforeRaw : null,
            limit: Number.isFinite(limitRaw) ? limitRaw : 20,
          }),
        });
        return true;
      }

      // GET /api/accounts/bookmarks
      if (method === "GET" && segments.length === 1 && segments[0] === "bookmarks") {
        const user = requireUser(req, res, limits.login);
        if (!user) return true;
        send(res, 200, store.social.bookmarksFor(user.id));
        return true;
      }

      // GET /api/accounts/notifications · POST marks everything read
      if (segments.length === 1 && segments[0] === "notifications") {
        const user = requireUser(req, res, limits.login);
        if (!user) return true;
        if (method === "GET") {
          handleNotifications(req, res, url, user);
          return true;
        }
        if (method === "POST") {
          store.transaction(() => store.social.markNotificationsRead(user.id));
          send(res, 200, { ok: true });
          return true;
        }
      }

      // GET /api/accounts/follow-requests — pending follows on private accounts
      if (method === "GET" && segments.length === 1 && segments[0] === "follow-requests") {
        const user = requireUser(req, res, limits.login);
        if (!user) return true;
        send(res, 200, { requests: store.social.pendingFollowers(user.id) });
        return true;
      }

      // POST /api/accounts/follow-requests/:followerId/accept|decline
      if (
        method === "POST" &&
        segments.length === 3 &&
        segments[0] === "follow-requests" &&
        (segments[2] === "accept" || segments[2] === "decline")
      ) {
        const user = requireUser(req, res, limits.socialAction);
        if (!user) return true;
        const followerId = decodeURIComponent(segments[1]);
        const handled = store.transaction(() =>
          store.social.respondFollow(followerId, user.id, segments[2] === "accept"),
        );
        if (!handled) {
          return fail(res, 404, "REQUEST_NOT_FOUND", "That follow request is gone.") || true;
        }
        send(res, 200, { ok: true });
        return true;
      }

      // POST /api/accounts/posts
      if (method === "POST" && segments.length === 1 && segments[0] === "posts") {
        const user = requireUser(req, res, limits.login);
        if (!user) return true;
        handleCreatePost(req, res, { body, user });
        return true;
      }

      // /api/accounts/posts/:id[/like|bookmark|report|comments]
      if (segments[0] === "posts" && segments.length >= 2) {
        const postId = decodeURIComponent(segments[1]);

        // GET/PATCH/DELETE /api/accounts/posts/:id
        if (segments.length === 2) {
          if (method === "GET") {
            const user = requireUser(req, res, limits.login);
            if (!user) return true;
            const post = withPost(res, user, postId);
            if (!post) return true;
            send(res, 200, { post: store.social.shapedPost(post, user.id) });
            return true;
          }
          if (method === "PATCH") {
            const user = requireUser(req, res, limits.socialPost);
            if (!user) return true;
            const post = store.social.postById(postId);
            if (!post || post.deleted_at) {
              return fail(res, 404, "POST_NOT_FOUND", "That post is gone.") || true;
            }
            if (post.author_id !== user.id) {
              return fail(res, 403, "NOT_AUTHOR", "Only the author can edit a post.") || true;
            }
            const postBody = validatePostBody(body.body);
            if (postBody.error) return fail(res, 400, "INVALID_POST", postBody.error) || true;
            const updated = store.transaction(() => store.social.editPost(postId, postBody.value));
            send(res, 200, { post: store.social.shapedPost(store.social.postById(postId), user.id), editedAt: updated.edited_at });
            return true;
          }
          if (method === "DELETE") {
            const user = requireUser(req, res, limits.socialPost);
            if (!user) return true;
            const post = store.social.postById(postId);
            if (!post || post.deleted_at) {
              return fail(res, 404, "POST_NOT_FOUND", "That post is gone.") || true;
            }
            if (post.author_id !== user.id && !isAdmin(user)) {
              return fail(res, 403, "NOT_AUTHOR", "Only the author (or an administrator) can delete a post.") || true;
            }
            store.transaction(() => store.social.deletePost(postId));
            send(res, 200, { ok: true });
            return true;
          }
        }

        // POST/DELETE /api/accounts/posts/:id/like
        if (segments.length === 3 && segments[2] === "like" && (method === "POST" || method === "DELETE")) {
          const user = requireUser(req, res, limits.socialAction);
          if (!user) return true;
          const post = withPost(res, user, postId);
          if (!post) return true;
          if (method === "DELETE") {
            store.transaction(() => {
              if (store.social.isPostLikedBy(postId, user.id)) store.social.toggleLike(postId, user.id);
            });
            send(res, 200, { liked: false });
            return true;
          }
          const liked = store.transaction(() => {
            if (store.social.isPostLikedBy(postId, user.id)) return false;
            store.social.toggleLike(postId, user.id);
            return true;
          });
          send(res, 200, { liked });
          return true;
        }

        // POST/DELETE /api/accounts/posts/:id/bookmark
        if (segments.length === 3 && segments[2] === "bookmark" && (method === "POST" || method === "DELETE")) {
          const user = requireUser(req, res, limits.socialAction);
          if (!user) return true;
          const post = withPost(res, user, postId);
          if (!post) return true;
          const bookmarked = store.transaction(() => {
            const isBookmarked = store.social.isBookmarkedBy(postId, user.id);
            if (method === "DELETE") {
              if (isBookmarked) store.social.toggleBookmark(postId, user.id);
              return false;
            }
            if (!isBookmarked) store.social.toggleBookmark(postId, user.id);
            return true;
          });
          send(res, 200, { bookmarked });
          return true;
        }

        // POST /api/accounts/posts/:id/report
        if (segments.length === 3 && segments[2] === "report" && method === "POST") {
          const user = requireUser(req, res, limits.socialPost);
          if (!user) return true;
          const post = store.social.postById(postId);
          if (!post || post.deleted_at) {
            return fail(res, 404, "POST_NOT_FOUND", "That post is gone.") || true;
          }
          const reason = validateReportReason(body.reason);
          if (reason.error) return fail(res, 400, "INVALID_REASON", reason.error) || true;
          store.transaction(() => store.social.reportPost(user.id, postId, reason.value));
          send(res, 201, { ok: true });
          return true;
        }

        // GET/POST /api/accounts/posts/:id/comments
        if (segments.length === 3 && segments[2] === "comments") {
          if (method === "GET") {
            const user = requireUser(req, res, limits.login);
            if (!user) return true;
            const post = withPost(res, user, postId);
            if (!post) return true;
            send(res, 200, { comments: store.social.commentsFor(postId, user.id) });
            return true;
          }
          if (method === "POST") {
            const user = requireUser(req, res, limits.socialComment);
            if (!user) return true;
            const post = withPost(res, user, postId);
            if (!post) return true;
            const comment = validateCommentBody(body.body);
            if (comment.error) return fail(res, 400, "INVALID_COMMENT", comment.error) || true;
            if (limitOr429(limits.socialComment, `comment:${user.id}`, res)) return true;
            const created = store.transaction(() => store.social.addComment(postId, user.id, comment.value));
            send(res, 201, { comment: created });
            return true;
          }
        }
      }

      // POST/DELETE /api/accounts/comments/:id/like · DELETE removes own comment
      if (segments[0] === "comments" && segments.length >= 2) {
        const commentId = decodeURIComponent(segments[1]);
        if (segments.length === 2 && method === "DELETE") {
          const user = requireUser(req, res, limits.socialAction);
          if (!user) return true;
          const verdict = store.transaction(() =>
            store.social.deleteComment(commentId, user.id, isAdmin(user)),
          );
          if (!verdict.found) return fail(res, 404, "COMMENT_NOT_FOUND", "That comment is gone.") || true;
          if (!verdict.allowed) return fail(res, 403, "NOT_AUTHOR", "Only the author (or an administrator) can delete a comment.") || true;
          send(res, 200, { ok: true });
          return true;
        }
        if (segments.length === 3 && segments[2] === "like" && (method === "POST" || method === "DELETE")) {
          const user = requireUser(req, res, limits.socialAction);
          if (!user) return true;
          const liked = store.transaction(() => {
            const isLiked = store.social.isCommentLikedBy(commentId, user.id);
            if (method === "DELETE") {
              if (isLiked) store.social.toggleCommentLike(commentId, user.id);
              return false;
            }
            if (!isLiked) store.social.toggleCommentLike(commentId, user.id);
            return true;
          });
          send(res, 200, { liked });
          return true;
        }
      }

      // /api/accounts/users/:username[/posts|follow|block]
      if (segments[0] === "users" && segments.length >= 2) {
        const username = segments[1];

        if (segments.length === 2 && method === "GET") {
          const user = requireUser(req, res, limits.login);
          if (!user) return true;
          handleProfileFetch(res, url, user, username);
          return true;
        }

        if (segments.length === 3 && segments[2] === "posts" && method === "GET") {
          const user = requireUser(req, res, limits.login);
          if (!user) return true;
          const target = store.social.userByUsername(decodeURIComponent(username));
          if (!target) return fail(res, 404, "ACCOUNT_NOT_FOUND", "That account no longer exists.") || true;
          if (store.social.isBlockedEither(user.id, target.id)) {
            return fail(res, 403, "BLOCKED", "You cannot view that account.") || true;
          }
          const beforeRaw = Number(url.searchParams.get("before") ?? 0);
          const limitRaw = Number(url.searchParams.get("limit") ?? 20);
          const page = store.social.postsByAuthor(user.id, target.id, {
            before: Number.isFinite(beforeRaw) && beforeRaw > 0 ? beforeRaw : null,
            limit: Number.isFinite(limitRaw) ? limitRaw : 20,
          });
          send(res, 200, page);
          return true;
        }

        if (segments.length === 3 && segments[2] === "follow" && (method === "POST" || method === "DELETE")) {
          const user = requireUser(req, res, limits.socialAction);
          if (!user) return true;
          const target = store.social.userByUsername(decodeURIComponent(username));
          if (!target) return fail(res, 404, "ACCOUNT_NOT_FOUND", "That account no longer exists.") || true;
          if (target.id === user.id) {
            return fail(res, 400, "SELF_FOLLOW", "You cannot follow yourself.") || true;
          }
          if (store.social.isBlockedEither(user.id, target.id)) {
            return fail(res, 403, "BLOCKED", "You cannot interact with that account.") || true;
          }
          if (method === "DELETE") {
            store.transaction(() => store.social.unfollow(user.id, target.id));
            send(res, 200, { following: false });
            return true;
          }
          const status = store.transaction(() => store.social.requestFollow(user.id, target.id));
          send(res, 200, { following: status === "accepted", pending: status === "pending" });
          return true;
        }

        if (segments.length === 3 && segments[2] === "block" && (method === "POST" || method === "DELETE")) {
          const user = requireUser(req, res, limits.socialAction);
          if (!user) return true;
          const target = store.social.userByUsername(decodeURIComponent(username));
          if (!target) return fail(res, 404, "ACCOUNT_NOT_FOUND", "That account no longer exists.") || true;
          if (target.id === user.id) {
            return fail(res, 400, "SELF_BLOCK", "You cannot block yourself.") || true;
          }
          store.transaction(() => store.social.setBlocked(user.id, target.id, method === "POST"));
          send(res, 200, { blocked: method === "POST" });
          return true;
        }
      }

      // GET /api/accounts/reports · POST /api/accounts/reports/:id/resolve (admin)
      if (segments[0] === "reports") {
        const user = requireUser(req, res, limits.login);
        if (!user) return true;
        if (!isAdmin(user)) {
          return fail(res, 403, "NOT_ADMIN", "Moderator tools are for administrators.") || true;
        }
        if (segments.length === 1 && method === "GET") {
          send(res, 200, { reports: store.social.openReports() });
          return true;
        }
        if (segments.length === 3 && segments[2] === "resolve" && method === "POST") {
          const reportId = decodeURIComponent(segments[1]);
          const resolution = cleanText(String(body.resolution ?? "resolved")).slice(0, 200);
          const removePost = body.removePost === true;
          store.transaction(() => store.social.resolveReport(reportId, resolution, body.postId, removePost));
          send(res, 200, { ok: true });
          return true;
        }
      }

      // POST /api/accounts/admin/users/:username/tags { tags: [...] } (admin)
      //
      // Tags are labels worn beside a name everywhere the account appears.
      // Only administrators set them, and they grant nothing: authority lives
      // in users.role, never in a label.
      if (
        segments[0] === "admin" &&
        segments[1] === "users" &&
        segments.length === 4 &&
        segments[3] === "tags" &&
        method === "POST"
      ) {
        const user = requireUser(req, res, limits.socialAction);
        if (!user) return true;
        if (!isAdmin(user)) {
          return fail(res, 403, "NOT_ADMIN", "Tags are set by administrators.");
        }
        const checked = validateTags(body.tags ?? []);
        if (checked.error) return fail(res, 400, "INVALID_TAGS", checked.error);
        const username = decodeURIComponent(segments[2]).toLowerCase();
        const target = store.db.prepare("SELECT id FROM users WHERE username_lower = ?").get(username);
        if (!target) return fail(res, 404, "USER_NOT_FOUND", "No account with that username.");
        store.db.prepare("UPDATE users SET tags = ? WHERE id = ?").run(JSON.stringify(checked.value), target.id);
        send(res, 200, { user: publicUser(store.db.prepare("SELECT * FROM users WHERE id = ?").get(target.id)) });
        return true;
      }

      /* ---- Crystal Chat servers ---- */

      // GET /api/accounts/servers · POST creates one
      if (segments.length === 1 && segments[0] === "servers") {
        const user = requireUser(req, res, limits.login);
        if (!user) return true;
        if (method === "GET") {
          send(res, 200, { servers: store.servers.myServers(user.id) });
          return true;
        }
        if (method === "POST") {
          if (limitOr429(limits.socialPost, `server-create:${user.id}`, res)) return true;
          const name = cleanText(String(body.name ?? "")).trim().slice(0, 60);
          if (!name) return fail(res, 400, "INVALID_NAME", "A server needs a name.") || true;
          const description = cleanText(String(body.description ?? "")).trim().slice(0, 400) || null;
          const icon = typeof body.icon === "string" && body.icon.length <= 512 * 1024 ? body.icon : null;
          const server = store.servers.createServer(user.id, { name, description, icon });
          send(res, 201, { server });
          return true;
        }
      }

      // /api/accounts/invites/:code[/join] — preview, join, revoke
      if (
        (segments.length === 3 || segments.length === 2) &&
        segments[0] === "invites"
      ) {
        const code = decodeURIComponent(segments[1]);
        const user = requireUser(req, res, limits.socialAction);
        if (!user) return true;
        if (method === "GET") {
          const invite = store.db
            .prepare("SELECT server_id FROM invites WHERE code = ? AND revoked_at IS NULL")
            .get(String(code).toUpperCase());
          if (!invite) return fail(res, 404, "INVITE_INVALID", "That invite no longer works.") || true;
          send(res, 200, { serverId: invite.server_id });
          return true;
        }
        if (method === "POST" && segments[2] === "join") {
          const result = store.servers.joinByInvite(code, user.id);
          send(res, result.alreadyMember ? 200 : 201, result);
          return true;
        }
        if (method === "DELETE") {
          store.servers.revokeInvite(code, user.id);
          send(res, 200, { ok: true });
          return true;
        }
      }

      // /api/accounts/servers/:id/...
      if (segments[0] === "servers" && segments.length >= 2) {
        const serverId = decodeURIComponent(segments[1]);

        if (segments.length === 2) {
          if (method === "GET") {
            const user = requireUser(req, res, limits.login);
            if (!user) return true;
            send(res, 200, store.servers.serverDetail(serverId, user.id));
            return true;
          }
          if (method === "PATCH") {
            const user = requireUser(req, res, limits.socialAction);
            if (!user) return true;
            const patch = {};
            if (body.name !== undefined) patch.name = String(body.name).slice(0, 60);
            if (body.description !== undefined) patch.description = String(body.description).slice(0, 400);
            if (body.icon !== undefined) patch.icon = String(body.icon).slice(0, 512 * 1024);
            send(res, 200, { server: store.servers.updateServer(serverId, user.id, patch) });
            return true;
          }
          if (method === "DELETE") {
            const user = requireUser(req, res, limits.socialAction);
            if (!user) return true;
            store.servers.deleteServer(serverId, user.id);
            send(res, 200, { ok: true });
            return true;
          }
        }

        // POST /api/accounts/servers/:id/transfer { username }
        if (segments.length === 3 && segments[2] === "transfer" && method === "POST") {
          const user = requireUser(req, res, limits.socialAction);
          if (!user) return true;
          const target = store.social.userByUsername(String(body.username ?? ""));
          if (!target) return fail(res, 404, "ACCOUNT_NOT_FOUND", "That account no longer exists.") || true;
          store.servers.transferOwnership(serverId, user.id, target.id);
          send(res, 200, { ok: true });
          return true;
        }

        // POST /api/accounts/servers/:id/channels
        if (segments.length === 3 && segments[2] === "channels" && method === "POST") {
          const user = requireUser(req, res, limits.socialAction);
          if (!user) return true;
          const channel = store.servers.addChannel(serverId, user.id, {
            name: String(body.name ?? ""),
            category: body.category,
            description: body.description,
            requiresPermission: body.requiresPermission ?? null,
          });
          send(res, 201, { channel });
          return true;
        }

        // GET /api/accounts/servers/:id/roles · POST creates one
        if (segments.length === 3 && segments[2] === "roles") {
          const user = requireUser(req, res, limits.socialAction);
          if (!user) return true;
          if (method === "GET") {
            const detail = store.servers.serverDetail(serverId, user.id);
            send(res, 200, { roles: detail.roles });
            return true;
          }
          if (method === "POST") {
            const role = store.servers.createRole(serverId, user.id, {
              name: body.name,
              color: body.color,
              permissions: body.permissions,
            });
            send(res, 201, { role });
            return true;
          }
        }

        // GET /api/accounts/servers/:id/members
        if (segments.length === 3 && segments[2] === "members" && method === "GET") {
          const user = requireUser(req, res, limits.login);
          if (!user) return true;
          send(res, 200, { members: store.servers.membersFor(serverId) });
          return true;
        }

        // PUT /api/accounts/servers/:id/members/:userId/role
        if (
          segments.length === 5 &&
          segments[2] === "members" &&
          segments[4] === "role" &&
          method === "PUT"
        ) {
          const user = requireUser(req, res, limits.socialAction);
          if (!user) return true;
          store.servers.assignRole(serverId, user.id, decodeURIComponent(segments[3]), body.roleId ?? null);
          send(res, 200, { ok: true });
          return true;
        }

        // DELETE /api/accounts/servers/:id/members/:userId (kick)
        if (segments.length === 4 && segments[2] === "members" && method === "DELETE") {
          const user = requireUser(req, res, limits.socialAction);
          if (!user) return true;
          store.servers.kickMember(serverId, user.id, decodeURIComponent(segments[3]));
          send(res, 200, { ok: true });
          return true;
        }

        // POST /api/accounts/servers/:id/invites · GET lists them
        if (segments.length === 3 && segments[2] === "invites") {
          const user = requireUser(req, res, limits.socialAction);
          if (!user) return true;
          if (method === "GET") {
            send(res, 200, { invites: store.servers.listInvites(serverId, user.id) });
            return true;
          }
          if (method === "POST") {
            const invite = store.servers.createInvite(serverId, user.id, {
              expiresInMs: body.expiresInMs,
              maxUses: body.maxUses,
            });
            send(res, 201, { invite });
            return true;
          }
        }

        // GET /api/accounts/servers/:id/audit
        if (segments.length === 3 && segments[2] === "audit" && method === "GET") {
          const user = requireUser(req, res, limits.login);
          if (!user) return true;
          send(res, 200, { audit: store.servers.auditFor(serverId, user.id) });
          return true;
        }
      }

      // /api/accounts/channels/:id[/messages] and role/message mutations
      if (segments[0] === "channels" && segments.length >= 2) {
        const channelId = decodeURIComponent(segments[1]);

        // GET/POST /api/accounts/channels/:id/messages
        if (segments.length === 3 && segments[2] === "messages") {
          if (method === "GET") {
            const user = requireUser(req, res, limits.login);
            if (!user) return true;
            const beforeRaw = Number(url.searchParams.get("before") ?? 0);
            const limitRaw = Number(url.searchParams.get("limit") ?? 50);
            send(
              res,
              200,
              store.servers.messagesFor(channelId, user.id, {
                before: Number.isFinite(beforeRaw) && beforeRaw > 0 ? beforeRaw : null,
                limit: Number.isFinite(limitRaw) ? limitRaw : 50,
              }),
            );
            return true;
          }
          if (method === "POST") {
            const user = requireUser(req, res, limits.message);
            if (!user) return true;
            const clientId =
              typeof body.clientId === "string" && /^[A-Za-z0-9_-]{6,64}$/.test(body.clientId)
                ? body.clientId
                : undefined;
            const message = store.servers.postMessage(channelId, user.id, body.body, clientId);
            send(res, 201, { message });
            return true;
          }
        }

        // PATCH /api/accounts/channels/:id — channel settings
        if (segments.length === 2 && method === "PATCH") {
          const user = requireUser(req, res, limits.socialAction);
          if (!user) return true;
          send(res, 200, { channel: store.servers.updateChannel(channelId, user.id, body) });
          return true;
        }
        if (segments.length === 2 && method === "DELETE") {
          const user = requireUser(req, res, limits.socialAction);
          if (!user) return true;
          store.servers.deleteChannel(channelId, user.id);
          send(res, 200, { ok: true });
          return true;
        }
      }

      // /api/accounts/roles/:id — edit/delete; /server-messages/:id — edit/delete
      if (segments[0] === "roles" && segments.length === 2) {
        const roleId = decodeURIComponent(segments[1]);
        const user = requireUser(req, res, limits.socialAction);
        if (!user) return true;
        if (method === "PATCH") {
          send(res, 200, { role: store.servers.updateRole(roleId, user.id, body) });
          return true;
        }
        if (method === "DELETE") {
          store.servers.deleteRole(roleId, user.id);
          send(res, 200, { ok: true });
          return true;
        }
      }

      if (segments[0] === "server-messages" && segments.length === 2) {
        const messageId = decodeURIComponent(segments[1]);
        const user = requireUser(req, res, limits.message);
        if (!user) return true;
        if (method === "PATCH") {
          store.servers.editMessage(messageId, user.id, body.body);
          send(res, 200, { ok: true });
          return true;
        }
        if (method === "DELETE") {
          store.servers.deleteMessage(messageId, user.id, isAdmin(user));
          send(res, 200, { ok: true });
          return true;
        }
      }

      // /api/accounts/conversations/:peerId/messages
      if (segments[0] === "conversations" && segments.length === 3 && segments[2] === "messages") {
        const user = requireUser(req, res);
        if (!user) return true;
        const peerId = decodeURIComponent(segments[1]);
        if (method === "GET") {
          handleConversationHistory(req, res, url, peerId, user);
          return true;
        }
        if (method === "POST") {
          handleSendMessage(req, res, peerId, { body, user });
          return true;
        }
      }

      /* ---- Store submissions ------------------------------------------- */

      if (segments[0] === "store") {
        // GET /api/accounts/store/approved — public catalogue of approved apps
        if (segments.length === 2 && segments[1] === "approved" && method === "GET") {
          send(res, 200, { submissions: store.appStore.approved() });
          return true;
        }

        // GET /api/accounts/store/mine — your own submissions and their state
        if (segments.length === 2 && segments[1] === "mine" && method === "GET") {
          const user = requireUser(req, res, limits.login);
          if (!user) return true;
          send(res, 200, { submissions: store.appStore.mine(user.id) });
          return true;
        }

        // POST /api/accounts/store/submit — propose a web application
        if (segments.length === 2 && segments[1] === "submit" && method === "POST") {
          const user = requireUser(req, res, limits.socialPost);
          if (!user) return true;
          const checked = validateSubmission(body);
          if (checked.error) return fail(res, 400, "INVALID_SUBMISSION", checked.error);
          send(res, 201, { submission: store.appStore.submit(user.id, checked.value) });
          return true;
        }

        // GET /api/accounts/store/admin?status=pending — the moderation queue
        if (segments.length === 2 && segments[1] === "admin" && method === "GET") {
          const user = requireUser(req, res, limits.login);
          if (!user) return true;
          if (!isAdmin(user)) {
            return fail(res, 403, "NOT_AUTHORIZED", "Only store moderators can read the queue.");
          }
          const status = url.searchParams.get("status") ?? "pending";
          send(res, 200, {
            submissions: store.appStore.listByStatus(status),
            pendingCount: store.appStore.pendingCount(),
          });
          return true;
        }

        // POST /api/accounts/store/admin/:id/review { action, note }
        if (
          segments.length === 4 &&
          segments[1] === "admin" &&
          segments[3] === "review" &&
          method === "POST"
        ) {
          const user = requireUser(req, res, limits.socialAction);
          if (!user) return true;
          if (!isAdmin(user)) {
            return fail(res, 403, "NOT_AUTHORIZED", "Only store moderators can review submissions.");
          }
          const checked = validateReview(body);
          if (checked.error) return fail(res, 400, "INVALID_REVIEW", checked.error);
          const result = store.appStore.review(
            decodeURIComponent(segments[2]),
            user.id,
            checked.value.action,
            checked.value.note,
          );
          if (result.error) return fail(res, 404, "SUBMISSION_NOT_FOUND", result.error);
          send(res, 200, { submission: result.value });
          return true;
        }
      }
    } catch (error) {
      // A refusal with a name and a sentence (permission, rank, missing
      // channel) is answered as itself; everything else is a plain 500.
      if (error instanceof ServerError) {
        fail(res, error.status, error.code, error.message);
        return true;
      }
      // Never leak a stack trace or a SQL statement to the client.
      process.stderr.write(`[accounts] ${method} ${path} failed: ${error?.message ?? error}\n`);
      if (!res.headersSent) {
        fail(res, 500, "SERVER_ERROR", "The account server could not complete that request.");
      }
      return true;
    }

    fail(res, 404, "NOT_FOUND", "No such account endpoint.");
    return true;
  }

  return { handle, store, limits, sessionDays };
}

/** Convenience for `server/scramjet/index.js` and the tests. */
export function listen(api, { port = 0, host = "127.0.0.1" } = {}) {
  const server = createServer((req, res) => {
    const url = new URL(req.url ?? "/", `http://${req.headers.host ?? "localhost"}`);
    void api.handle(req, res, url).then((handled) => {
      if (!handled && !res.headersSent) {
        res.writeHead(404, { "content-type": "text/plain; charset=utf-8" });
        res.end("Not found.");
      }
    });
  });
  return new Promise((resolve, reject) => {
    server.once("error", reject);
    server.listen(port, host, () => resolve(server));
  });
}
