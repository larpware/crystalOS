/* ==========================================================================
   Shared Scramjet service

   One controller for the whole OS. Browser, Drive, Spotify and Audiomack all
   create their frames here, so they share the controller, the transport and the
   service-worker registration instead of initialising four incompatible
   clients. Frames are per-window, which is what makes several proxied
   applications work at the same time.

   Initialisation follows the official bootstrap flow: load
   /bootstrap-init.js (generated by server/scramjet/assets.mjs around the
   official client bundle), call initBootstrap(), then wait for the controller.
   Nothing about the transport is invented here — the transport, and the files
   backing it, are whatever the backend serves (see server/scramjet/assets.mjs,
   which takes them from scramjet-assets/ before anything else).
   ========================================================================== */

export type ScramjetStatus = "idle" | "loading" | "ready" | "error";

export interface ScramjetAssetPackage {
  version: string;
  /** Where the backend found it: `scramjet-assets/…`, `node_modules/…`, … */
  source: string;
}

/** What the backend reported about the files it serves the proxy. */
export interface ScramjetAssets {
  dir: string;
  transport: string;
  packages: Record<string, ScramjetAssetPackage>;
  missing: { url: string; package: string; file: string }[];
}

export interface ScramjetState {
  status: ScramjetStatus;
  /** Human-readable reason the proxy cannot start. */
  error: string | null;
  transport: string | null;
  /** Result of the most recent backend probe. */
  backendReachable: boolean | null;
  /** Asset provenance from the backend, once it has answered. */
  assets: ScramjetAssets | null;
  attempts: number;
}

const initialState: ScramjetState = {
  status: "idle",
  error: null,
  transport: null,
  backendReachable: null,
  assets: null,
  attempts: 0,
};

let state: ScramjetState = initialState;
let controller: ScramjetController | null = null;
let pending: Promise<ScramjetController> | null = null;
const listeners = new Set<(state: ScramjetState) => void>();

function publish(patch: Partial<ScramjetState>): void {
  state = { ...state, ...patch };
  for (const listener of listeners) listener(state);
}

export function getScramjetState(): ScramjetState {
  return state;
}

export function subscribeScramjet(listener: (state: ScramjetState) => void): () => void {
  listeners.add(listener);
  listener(state);
  return () => listeners.delete(listener);
}

/** Hook-friendly subscription for React's `useSyncExternalStore`. */
export function subscribeScramjetStore(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

/** The controller is a module singleton; scripts are only fetched once. */
function loadScriptOnce(src: string): Promise<void> {
  const existing = document.querySelector<HTMLScriptElement>(`script[data-scramjet="${src}"]`);
  if (existing?.dataset.loaded === "true") return Promise.resolve();
  return new Promise((resolve, reject) => {
    const script = existing ?? document.createElement("script");
    script.src = src;
    script.dataset.scramjet = src;
    script.dataset.loaded = "false";
    script.addEventListener("load", () => {
      script.dataset.loaded = "true";
      resolve();
    });
    script.addEventListener("error", () => {
      script.remove();
      reject(new Error(`Could not load ${src}.`));
    });
    if (!existing) document.head.appendChild(script);
  });
}

const BACKEND_HELP =
  "The Scramjet backend is not answering on this origin. Start it with `npm run scramjet` (or `npm run dev:all` while developing), then retry.";

interface BackendStatus {
  ok: boolean;
  transport?: string;
  assets?: ScramjetAssets;
}

/**
 * Asks the backend for its real status before touching the service worker, so a
 * missing backend produces one clear message instead of a broken frame.
 *
 * When the OS is working offline the request is refused rather than attempted
 * by API convention further up; either way the answer is the same, so this only
 * has to name it.
 */
async function probeBackend(): Promise<BackendStatus> {
  const response = await fetch("/api/proxy-status", { cache: "no-store" });
  if (!response.ok) throw new Error(`Backend status ${response.status}`);
  return (await response.json()) as BackendStatus;
}

/** Why the proxy cannot start, said in the terms the user is actually in. */
function backendUnavailableHelp(): string {
  const report = currentOffline();
  if (!report.offline) return BACKEND_HELP;
  return `${offlineHeadline(report)}. ${offlineExplanation(report)} Proxied pages need the Scramjet backend, which needs the network.`;
}

async function createController(): Promise<ScramjetController> {
  publish({ status: "loading", error: null, attempts: state.attempts + 1, backendReachable: null });

  let backend: BackendStatus;
  try {
    backend = await probeBackend();
    publish({ assets: backend.assets ?? null });
  } catch {
    const help = backendUnavailableHelp();
    // Whatever the previous probe said about the files is no longer true.
    publish({ status: "error", error: help, backendReachable: false, assets: null });
    throw new Error(help);
  }

  try {
    await loadScriptOnce("/bootstrap-init.js");
  } catch (error) {
    const message =
      error instanceof Error
        ? `${error.message} ${BACKEND_HELP}`
        : BACKEND_HELP;
    publish({ status: "error", error: message, backendReachable: true });
    throw new Error(message);
  }

  if (typeof window.initBootstrap !== "function") {
    const message =
      "The Scramjet bootstrap loaded but did not expose initBootstrap(). Check that the backend is serving /bootstrap-init.js.";
    publish({ status: "error", error: message, backendReachable: true });
    throw new Error(message);
  }

  if (!navigator.serviceWorker) {
    const message =
      "This browser exposes no service workers, so Scramjet cannot route proxied requests. Proxied applications cannot start here.";
    publish({ status: "error", error: message, backendReachable: true });
    throw new Error(message);
  }

  try {
    const created = await window.initBootstrap();
    await created.wait();
    await waitForScopeServiceWorker();
    controller = created;
    publish({
      status: "ready",
      error: null,
      backendReachable: true,
      transport: backend.transport ?? null,
    });
    return created;
  } catch (error) {
    const message = `Scramjet failed to start: ${
      error instanceof Error ? error.message : String(error)
    }`;
    publish({ status: "error", error: message, backendReachable: true });
    throw new Error(message);
  }
}

/**
 * Waits (briefly) for a service worker to reach `active` for this scope.
 *
 * The controller being ready is not the same as the worker being able to
 * intercept: a frame whose first navigation outruns activation has its request
 * fall through to the server, whose SPA fallback answers with the shell — a
 * second CrystalOS boots inside the frame. Waiting here closes that race at
 * the source; the bounded wait means a worker that never activates still
 * proceeds to an honest failure further down rather than hanging.
 */
async function waitForScopeServiceWorker(timeoutMs = 2_500): Promise<void> {
  if (!navigator.serviceWorker) return;
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    try {
      const registration = await navigator.serviceWorker.getRegistration();
      if (registration?.active) return;
      const worker = registration?.installing ?? registration?.waiting ?? null;
      if (!worker) {
        // Registration itself may still be in flight; poll until the deadline.
        await new Promise((resolve) => window.setTimeout(resolve, 100));
        continue;
      }
      await new Promise((resolve) => {
        const done = () => {
          worker.removeEventListener("statechange", done);
          resolve(undefined);
        };
        worker.addEventListener("statechange", done);
      });
    } catch {
      return;
    }
  }
}

/** Resolves with the shared controller, starting it on first use. */
export function ensureScramjet(): Promise<ScramjetController> {
  if (controller) return Promise.resolve(controller);
  if (pending) return pending;
  pending = createController().catch((error: unknown) => {
    pending = null;
    throw error;
  });
  return pending;
}

/** Clears a failed state so the next attempt starts from scratch. */
export function retryScramjet(): Promise<ScramjetController> {
  pending = null;
  controller = null;
  publish({ status: "idle", error: null });
  return ensureScramjet();
}

export interface ProxiedFrameHandle {
  frame: ScramjetFrame;
  dispose: () => void;
}

export interface CreateFrameOptions {
  onUrl?: (url: string) => void;
  /** Links that try to escape the frame (target=_blank, window.open). */
  onEscapedLink?: (url: URL) => void;
  /**
   * A request for the frame's own document that the transport could not
   * complete. Reported as it happens, before anything is rendered, so the
   * caller can fail with the reason instead of leaving a pane empty.
   */
  onFailure?: (failure: FrameFailure) => void;
  plugins?: ScramjetPlugin[];
  /**
   * What Shield's counters belong to — a browser tab id, a window, an app.
   * Without one the blocked count is shared, which is still honest but less
   * useful.
   */
  owner?: string | null;
}

/** Compares two URLs ignoring the fragment, so a hash change is not a new page. */
function withoutHash(url: string): string {
  const hash = url.indexOf("#");
  return hash < 0 ? url : url.slice(0, hash);
}

/**
 * Creates a Scramjet frame for one application window. Every caller gets its
 * own frame, so several proxied windows coexist without sharing history.
 */
export async function createProxiedFrame(
  element: HTMLIFrameElement,
  options: CreateFrameOptions = {},
): Promise<ProxiedFrameHandle> {
  const active = await ensureScramjet();
  const utils = window.$scramjetUtils;
  const plugins: ScramjetPlugin[] = [...(options.plugins ?? [])];

  if (utils) {
    plugins.push(new utils.HttpCachePlugin());

    // Shield is installed before the URL watcher so it is in place for the
    // frame's very first request, and so its counters can be reset here when
    // the frame really moves to a different page.
    const owner = options.owner ?? null;
    const shield = createShieldPlugin({ owner });
    if (shield) plugins.push(shield);

    if (options.onUrl) {
      let lastUrl: string | null = null;
      plugins.push(
        new utils.UrlWatcherPlugin((url) => {
          if (owner && (lastUrl === null || withoutHash(lastUrl) !== withoutHash(url))) {
            resetBlocked(owner);
          }
          lastUrl = url;
          options.onUrl?.(url);
        }),
      );
    }

    // A failed document request is reported as it happens, so a frame that will
    // never render says why instead of showing an empty pane.
    if (options.onFailure) {
      const reporter = createFailureReporterPlugin({ onFailure: options.onFailure });
      if (reporter) plugins.push(reporter);
    }

    if (options.onEscapedLink) {
      plugins.push(new utils.CatchEscapedLinksPlugin(options.onEscapedLink));
    }
  }

  const frame = active.createFrame(element, { plugins });
  return {
    frame,
    dispose: () => {
      const index = active.frames.indexOf(frame);
      if (index >= 0) active.frames.splice(index, 1);
      frame.element.removeAttribute("src");
    },
  };
}

