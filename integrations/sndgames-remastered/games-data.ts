export function getSlug(url: string): string {
  try {
    const u = new URL(url)
    // For crazygames embed URLs, extract the slug for thumbnail
    if (u.hostname.includes("crazygames.com")) {
      return u.pathname.split("/embed/")[1] || ""
    }
    // For gamedistribution, extract the md5 hash
    if (u.hostname.includes("html5.gamedistribution.com")) {
      const parts = u.pathname.split("/").filter(Boolean);
      return parts.length > 0 ? parts[0] : "";
    }
    return ""
  } catch {
    return ""
  }
}

export function getThumbnail(url: string): string | null {
  const slug = getSlug(url)
  if (slug) {
    if (url.includes("crazygames.com")) {
      return `https://images.crazygames.com/games/${slug}/cover-1695108717043.png?auto=format%2Ccompress&q=45&cs=strip&ch=DPR&w=400`
    }
    if (url.includes("gamedistribution.com")) {
      return `https://img.gamedistribution.com/${slug}-512x384.jpg`
    }
  }
  return null
}
